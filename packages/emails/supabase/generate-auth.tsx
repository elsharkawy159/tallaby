/**
 * Renders the Claude Design auth emails (Welcome/Verify, Password Reset) to
 * Supabase templates with Go placeholders, overwriting
 * `confirm-signup.ar.html` and `reset-password.ar.html`:
 *
 *   pnpm --filter @workspace/emails supabase:auth
 *
 * Then paste each file into Supabase → Authentication → Email Templates.
 */
import { writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { render } from "@react-email/components";
import { createElement } from "react";
import { PasswordResetEmail, WelcomeVerifyEmail } from "../src/index.js";

const dir = dirname(fileURLToPath(import.meta.url));
const props = { locale: "ar" as const, email: "{{ .Email }}", actionUrl: "{{ .ConfirmationURL }}" };

const header = (slot: string) =>
  `<!-- Supabase Auth → ${slot}. Generated by supabase/generate-auth.tsx from src/AuthEmails.tsx — edit those, not this file. -->\n`;

writeFileSync(
  join(dir, "confirm-signup.ar.html"),
  header("Confirm signup") + (await render(createElement(WelcomeVerifyEmail, props))),
);
writeFileSync(
  join(dir, "reset-password.ar.html"),
  header("Reset Password") + (await render(createElement(PasswordResetEmail, props))),
);
console.log("Wrote confirm-signup.ar.html and reset-password.ar.html");
