/**
 * Generates the SQL that seeds Tallaby Classic v2 in `template_versions`
 * (PLAN.md P4-03). Run `pnpm --filter @workspace/store-sections classic:sql`
 * after changing the template and commit the output as a new migration.
 */
import { validateSiteConfig } from "../config/validate";
import { TALLABY_CLASSIC_KEY, TALLABY_CLASSIC_VERSION, tallabyClassicConfig } from "./tallaby-classic";

export const CLASSIC_JSON_START = "-- classic-config:start";
export const CLASSIC_JSON_END = "-- classic-config:end";

export function classicTemplateConfigJson(): string {
  const result = validateSiteConfig(tallabyClassicConfig());
  if (!result.success) throw new Error(`Tallaby Classic is invalid: ${JSON.stringify(result.issues)}`);
  return JSON.stringify(result.data);
}

export function classicTemplateMigrationSql(migrationName: string): string {
  const json = classicTemplateConfigJson().replace(/'/g, "''");
  return `-- ${migrationName} (PLAN.md P4-03)
--
-- Tallaby Classic v${TALLABY_CLASSIC_VERSION}: the full classic template from
-- packages/store-sections/src/templates/tallaby-classic.ts (generated by
-- \`pnpm --filter @workspace/store-sections classic:sql\`; a test checks this
-- file matches). Replaces the v1 placeholder from 0052 as the current version.
--
-- Idempotent.

INSERT INTO template_versions (template_id, version, schema_version, config, changelog)
SELECT t.id, ${TALLABY_CLASSIC_VERSION}, 1,
${CLASSIC_JSON_START}
'${json}'::jsonb,
${CLASSIC_JSON_END}
  'Full Tallaby Classic: classic header, store front, category circles, all products, classic footer'
FROM templates t
WHERE t.key = '${TALLABY_CLASSIC_KEY}'
ON CONFLICT (template_id, version) DO NOTHING;

UPDATE templates t SET current_version_id = v.id, updated_at = now()
FROM template_versions v
WHERE t.key = '${TALLABY_CLASSIC_KEY}' AND v.template_id = t.id AND v.version = ${TALLABY_CLASSIC_VERSION}
  AND t.current_version_id IS DISTINCT FROM v.id;

-- Rollback: point templates.current_version_id back to version 1 and delete version ${TALLABY_CLASSIC_VERSION}.
`;
}
