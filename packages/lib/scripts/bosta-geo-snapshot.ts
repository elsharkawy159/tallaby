/**
 * Regenerates src/shipping/bosta/bosta-geo.data.ts from Bosta's public city
 * and district lists (no API key needed), plan §4.3:
 *
 *   pnpm --filter @workspace/lib bosta:geo
 *
 * Run it by hand when Bosta changes its zoning, review the diff, then run
 * the bosta-geo tests. Nothing calls Bosta's geography at runtime.
 */
import { writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const BASE = "https://app.bosta.co/api/v2";
const EGYPT_COUNTRY_ID = "60e4482c7cb7d4bc4849c4d5";
const OUT = resolve(dirname(fileURLToPath(import.meta.url)), "../src/shipping/bosta/bosta-geo.data.ts");

type City = { _id: string; name: string; nameAr: string; code: string; dropOffAvailability: boolean };
type District = {
  zoneId: string;
  zoneName: string;
  zoneOtherName: string;
  districtId: string;
  districtName: string;
  districtOtherName: string;
  dropOffAvailability: boolean;
};
type CityDistricts = { cityId: string; districts: District[] };

async function get<T>(path: string): Promise<T> {
  const response = await fetch(`${BASE}${path}`, { headers: { Accept: "application/json" } });
  if (!response.ok) throw new Error(`${path}: HTTP ${response.status}`);
  const body = (await response.json()) as { success?: boolean; data?: unknown };
  if (body.success === false) throw new Error(`${path}: success=false`);
  return body.data as T;
}

const q = (s: string) => JSON.stringify((s ?? "").trim());

async function main() {
  const citiesData = await get<{ list: City[] } | City[]>(`/cities?countryId=${EGYPT_COUNTRY_ID}`);
  const cities = (Array.isArray(citiesData) ? citiesData : citiesData.list).sort((a, b) => a.code.localeCompare(b.code));
  const groups = await get<CityDistricts[]>(`/cities/getAllDistricts?countryId=${EGYPT_COUNTRY_ID}`);
  const byCity = new Map(groups.map((g) => [g.cityId, g.districts]));

  const lines: string[] = [];
  lines.push("/* eslint-disable */");
  lines.push("// GENERATED by packages/lib/scripts/bosta-geo-snapshot.ts (pnpm --filter @workspace/lib bosta:geo).");
  lines.push(`// Source: ${BASE}/cities and /cities/getAllDistricts, ${new Date().toISOString().slice(0, 10)}. Do not edit by hand.`);
  lines.push("");
  lines.push("/** `[id, nameEn, nameAr, code, dropOff (1|0)]` */");
  lines.push("export type BostaCityRow = readonly [id: string, nameEn: string, nameAr: string, code: string, dropOff: 0 | 1];");
  lines.push("");
  lines.push("/**");
  lines.push(" * `[districtId, nameEn, nameAr, zoneId, zoneEn, zoneAr, dropOff (1|0)]`; the zone names are");
  lines.push(" * empty when they equal the district's.");
  lines.push(" */");
  lines.push(
    "export type BostaDistrictRow = readonly [districtId: string, nameEn: string, nameAr: string, zoneId: string, zoneEn: string, zoneAr: string, dropOff: 0 | 1];",
  );
  lines.push("");
  lines.push("export const BOSTA_CITIES: readonly BostaCityRow[] = [");
  for (const c of cities) lines.push(`  [${q(c._id)}, ${q(c.name)}, ${q(c.nameAr)}, ${q(c.code)}, ${c.dropOffAvailability ? 1 : 0}],`);
  lines.push("];");
  lines.push("");
  lines.push("export const BOSTA_DISTRICTS: Readonly<Record<string, readonly BostaDistrictRow[]>> = {");
  let total = 0;
  for (const c of cities) {
    const districts = byCity.get(c._id) ?? [];
    total += districts.length;
    lines.push(`  ${q(c._id)}: [`);
    for (const d of districts) {
      const zoneEn = d.zoneName?.trim() === d.districtName?.trim() ? "" : d.zoneName;
      const zoneAr = d.zoneOtherName?.trim() === d.districtOtherName?.trim() ? "" : d.zoneOtherName;
      lines.push(
        `    [${q(d.districtId)}, ${q(d.districtName)}, ${q(d.districtOtherName)}, ${q(d.zoneId)}, ${q(zoneEn)}, ${q(zoneAr)}, ${d.dropOffAvailability ? 1 : 0}],`,
      );
    }
    lines.push("  ],");
  }
  lines.push("};");
  lines.push("");

  writeFileSync(OUT, lines.join("\n"), "utf8");
  console.log(`Wrote ${cities.length} cities and ${total} districts to ${OUT}`);
}

main().catch((error) => {
  console.error(error);
  process.exit(1);
});
