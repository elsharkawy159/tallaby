function buildKnownSectionIds (): ReadonlySet<string> {
  const ids = new Set<string>(CURRENT_SECTION_IDS)
  for (const [legacy, current] of Object.entries(SECTION_ID_ALIASES)) {
    ids.add(legacy)
    ids.add(current)
  }
  return ids
}

